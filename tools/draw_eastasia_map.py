def paint(poly, e=None, c=None, only_land=True):
    """多边形填充；默认只改已画出的陆地格（地形颜料不抬升海洋），
    海岸线/岛屿绘制时传 only_land=False 直接落笔。"""
    m = Path(np.asarray(poly)).contains_points(
        np.vstack([LON.ravel(), LAT.ravel()]).T).reshape(H, W)
    if only_land:
        m &= elev > 0
    if e is not None:
        elev[m] = e
    if c is not None:
        clim[m] = c
    return int(m.sum())


def rect(lon0, lon1, lat0, lat1):
    return [(lon0, lat0), (lon1, lat0), (lon1, lat1), (lon0, lat1)]


