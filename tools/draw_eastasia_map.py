# ================================================================ 5. 确定性噪声
# 值噪声：12x8 随机格双线性插值。幅度压在不改变地块分类阈值的区间。
rng = np.random.default_rng(20240601)
coarse = rng.random((8, 12)) * 2.0 - 1.0
ys = np.linspace(0, 7, H)
xs = np.linspace(0, 11, W)
yi = ys.astype(int)
xi = xs.astype(int)
ty = ys - yi
tx = xs - xi
noise = np.zeros((H, W))
for dy in (0, 1):
    for dx in (0, 1):
        w = ((1 - ty) if dy == 0 else ty)[:, None] * \
            ((1 - tx) if dx == 0 else tx)[None, :]
        ys_c = np.clip(yi + dy, 0, 7)
        xs_c = np.clip(xi + dx, 0, 11)
        noise += coarse[ys_c[:, None], xs_c[None, :]] * w

