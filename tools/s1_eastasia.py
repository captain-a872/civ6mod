DLON = (LON1 - LON0) / W
DLAT = (LAT1 - LAT0) / H
lons = LON0 + (np.arange(W) + 0.5) * DLON
lats = LAT1 - (np.arange(H) + 0.5) * DLAT   # y=0 行=北纬 55（北行优先）
LON, LAT = np.meshgrid(lons, lats)          # LON[y,x], LAT[y,x]
PTS = np.column_stack([LON.ravel(), LAT.ravel()])

def mask_poly(verts):
    """verts: [(lon,lat),...] -> 布尔掩膜 (H,W)，按格心点在多边形内"""
    return Path(verts).contains_points(PTS).reshape(H, W)

def mask_near_line(line, radius_deg):
    """折线缓冲掩膜：格心到折线采样点 < radius_deg"""
    pts = []
    for (x0, y0), (x1, y1) in zip(line[:-1], line[1:]):
        n = max(2, int(np.hypot(x1 - x0, y1 - y0) / 0.25))
        xs = np.linspace(x0, x1, n); ys = np.linspace(y0, y1, n)
        pts.append(np.column_stack([xs, ys]))
    P = np.concatenate(pts)
    m = np.zeros(H * W, bool)
    for i in range(0, len(P), 1):
        d2 = (PTS[:, 0] - P[i, 0]) ** 2 + (PTS[:, 1] - P[i, 1]) ** 2
        m |= d2 < radius_deg ** 2
    return m.reshape(H, W)

